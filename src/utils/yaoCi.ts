export function getYaoCi(guaName: string, yaoNum: number): string {
  const yaoCiList = YAO_CI_MAP[guaName]
  if (yaoCiList && yaoCiList[yaoNum - 1]) {
    return yaoCiList[yaoNum - 1]
  }
  return `第${yaoNum}爻：爻辞暂未收录`
}